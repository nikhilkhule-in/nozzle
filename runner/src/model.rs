//! Workflow file format: what authors write.
//!
//! These types are the single source of truth for the loader *and* for the
//! JSON Schema contract (`nzl schema` / `just schema`), so the two
//! cannot drift apart.

use schemars::JsonSchema;
use serde::Deserialize;
use std::collections::BTreeMap;

/// Top-level workflow file: `name` plus `tasks`.
#[derive(Debug, Deserialize, JsonSchema)]
#[schemars(
    title = "Nozzle workflow",
    description = "A workflows-as-code file consumed by nzl: a workflow name plus a list of shell tasks with dependency edges. Written as YAML (.yaml/.yml) or JSON (.json); both forms parse into the same schema. Generated by `just schema` from the runner's loader types — do not hand-edit the output file."
)]
pub struct WorkflowYaml {
    /// Workflow id, shown in the run summary.
    #[schemars(regex(pattern = r"\S"))]
    pub name: String,
    /// Tasks in definition order; the engine runs the first ready task in
    /// this order.
    #[schemars(length(min = 1))]
    pub tasks: Vec<TaskYaml>,
}

/// One task: a shell command with optional ordering (`needs`),
/// data-flow (`env`) dependencies, container image, and explicit
/// environment passthrough (`passEnv`).
#[derive(Debug, Deserialize, JsonSchema)]
pub struct TaskYaml {
    /// Unique task identifier. Uniqueness (like all cross-references between
    /// ids) is enforced at runtime by the engine validator, not by the
    /// schema.
    #[schemars(regex(pattern = r"\S"))]
    pub id: String,
    /// Shell command, executed as `sh -c '<cmd>'` with the ambient
    /// environment plus injected bindings.
    #[schemars(regex(pattern = r"\S"))]
    pub cmd: String,
    /// Ordering dependencies: this task runs only after each listed task
    /// reaches a terminal state. Referenced ids must exist (runtime check).
    #[serde(default)]
    pub needs: Vec<String>,
    /// Environment bindings for this task: variable name -> upstream task
    /// id. Each binding injects the upstream task's captured stdout into
    /// this task's environment and implies a dependency on it.
    #[serde(default)]
    pub env: BTreeMap<String, String>,
    /// Container image for Docker execution (e.g. `rust:1.80`). Absent
    /// means local execution; Docker mode requires it per task.
    #[serde(default)]
    pub image: Option<String>,
    /// Explicit host environment allowlist forwarded to the task container.
    /// Missing names fail validation before any task runs. Local execution
    /// inherits ambient and ignores this beyond validation.
    #[serde(default, rename = "passEnv")]
    pub pass_env: Vec<String>,
}

#[cfg(test)]
mod tests {
    use super::*;

    const SAMPLE: &str = r#"
name: demo
tasks:
  - id: gen-tag
    cmd: echo "nozzle-1"
  - id: build
    cmd: docker build -t "$IMAGE_TAG" .
    needs: [gen-tag]
    env: { IMAGE_TAG: gen-tag }
"#;

    #[test]
    fn parses_sample_yaml() {
        let wf: WorkflowYaml = serde_yaml::from_str(SAMPLE).unwrap();
        assert_eq!(wf.name, "demo");
        assert_eq!(wf.tasks.len(), 2);
        assert_eq!(wf.tasks[0].id, "gen-tag");
        assert!(wf.tasks[0].needs.is_empty());
        assert!(wf.tasks[0].env.is_empty());
        assert_eq!(wf.tasks[1].needs, vec!["gen-tag".to_string()]);
        assert_eq!(
            wf.tasks[1].env.get("IMAGE_TAG").map(String::as_str),
            Some("gen-tag")
        );
    }

    #[test]
    fn missing_fields_are_parse_errors() {
        assert!(serde_yaml::from_str::<WorkflowYaml>("tasks: []").is_err());
        assert!(serde_yaml::from_str::<WorkflowYaml>("name: w\ntasks:\n  - id: a\n").is_err());
    }
}
